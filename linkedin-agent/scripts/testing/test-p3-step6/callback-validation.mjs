// ═══════════════════════════════════════════════════════════════
// Phase 3 Step 6 Groups 2-3: Callback Validation
// Verifies GET /auth/callback rejects invalid states, missing
// parameters, and Auth0 error responses.
// ═══════════════════════════════════════════════════════════════
import { group, groupEnd, test, testAsync, check, getCounters } from '../lib/test-harness.mjs';

var BASE = process.env.TEST_BASE_URL || 'http://127.0.0.1:3001';
var TIMEOUT = { signal: AbortSignal.timeout(10000) };

console.log('  File: test-p3-step6/callback-validation.mjs');
group('Group 2: Callback rejects invalid requests', `
  Impact: If these tests fail, an attacker can forge callback URLs
  that bypass state validation. They craft a link with a fake
  authorization code and state, and if the server accepts it,
  the attacker controls the session — accessing the dashboard
  as the victim.

  Route under test: GET /auth/callback
  Expected: 403 for invalid/missing state, error for Auth0 errors
  Defense: Server-side state validation, error parameter handling
`);

var before2 = getCounters();

await testAsync('3.6.2.1', ' Missing state parameter returns 403', async () => {
  console.log('  Sending GET /auth/callback?code=test_code (no state)');
  console.log('  Without state, the server cannot verify the request originated from /auth/login');
  console.log('  Checking: response status is 403');
  var res = await fetch(BASE + '/auth/callback?code=test_code', TIMEOUT);
  check('Missing state returns 403', res.status === 403, '403', String(res.status));
});

await testAsync('3.6.2.2', ' Empty state parameter returns 403', async () => {
  console.log('  Sending GET /auth/callback?code=test_code&state= (empty state)');
  console.log('  An empty state is not a valid CSRF token');
  console.log('  Checking: response status is 403');
  var res = await fetch(BASE + '/auth/callback?code=test_code&state=', TIMEOUT);
  check('Empty state returns 403', res.status === 403, '403', String(res.status));
});

await testAsync('3.6.2.3', ' Forged state returns 403', async () => {
  console.log('  Sending GET /auth/callback?code=test_code&state=attacker_forged_value');
  console.log('  This state was never generated by /auth/login — must be rejected');
  console.log('  Checking: response status is 403');
  var res = await fetch(BASE + '/auth/callback?code=test_code&state=attacker_forged_value', TIMEOUT);
  check('Forged state returns 403', res.status === 403, '403', String(res.status));
});

await testAsync('3.6.2.4', ' 64-char hex state that was never generated returns 403', async () => {
  console.log('  Sending a correctly formatted state (64 hex chars) that the server never issued');
  console.log('  The server must check its pending state set, not just the format');
  console.log('  Checking: response status is 403');
  var res = await fetch(BASE + '/auth/callback?code=test_code&state=' + 'ab'.repeat(32), TIMEOUT);
  check('Non-generated hex state returns 403', res.status === 403, '403', String(res.status));
});

await testAsync('3.6.2.5', ' Missing code parameter is handled', async () => {
  console.log('  Sending GET /auth/callback?state=forged_state (no code parameter)');
  console.log('  Without a code, there is nothing to exchange for tokens');
  console.log('  The server should return an error (403 for bad state, or 400 for missing code)');
  console.log('  Checking: response status is 4xx (not 200 or 500)');
  var res = await fetch(BASE + '/auth/callback?state=forged_state', TIMEOUT);
  check('Missing code handled', res.status >= 400 && res.status < 500, '4xx', String(res.status));
});

await testAsync('3.6.2.6', ' State consumed after use cannot be replayed', async () => {
  console.log('  Step 1: GET /auth/login to generate a valid state');
  console.log('  Step 2: Extract the state from the redirect URL');
  console.log('  Step 3: Use the state in a callback request (will fail on code exchange, but state is consumed)');
  console.log('  Step 4: Use the same state again — must be rejected');
  console.log('  Checking: second use of same state returns 403');
  var loginRes = await fetch(BASE + '/auth/login', { ...TIMEOUT, redirect: 'manual' });
  var location = loginRes.headers?.get('location') || '';
  var state = '';
  try { state = new URL(location).searchParams.get('state') || ''; } catch {}
  if (!state) { check('State extracted from login', false, 'state value', 'no state'); return; }

  // First callback — state is valid but code exchange will fail (no real Auth0 code)
  // The server consumes the state regardless of code exchange outcome
  await fetch(BASE + '/auth/callback?code=fake_code&state=' + state, TIMEOUT);

  // Second callback with same state — must be rejected
  var replayRes = await fetch(BASE + '/auth/callback?code=fake_code&state=' + state, TIMEOUT);
  check('Replayed state returns 403', replayRes.status === 403, '403', String(replayRes.status));
});

await testAsync('3.6.2.7', ' Callback error response does not leak internals', async () => {
  console.log('  Sending a callback with invalid state and checking the error body');
  console.log('  The response must not contain stack traces, file paths, or Auth0 client_secret');
  console.log('  Checking: body does not contain .js: or node_modules or client_secret');
  var res = await fetch(BASE + '/auth/callback?code=x&state=bad', TIMEOUT);
  var body = await res.text();
  var leaks = body.includes('.js:') || body.includes('node_modules') || body.includes('client_secret');
  check('No internals in callback error', !leaks, 'clean', body.substring(0, 80));
});

var after2 = getCounters();
groupEnd(after2.pass - before2.pass, after2.fail - before2.fail);

console.log('  File: test-p3-step6/callback-validation.mjs');
group('Group 3: Auth0 error parameter handling', `
  Impact: If Auth0 returns an error instead of a code (user denies
  consent, misconfigured app, expired link), the callback receives
  ?error=...&error_description=... instead of ?code=...&state=...
  The server must handle this gracefully, not crash or leak details.

  Route under test: GET /auth/callback?error=...
`);

var before3 = getCounters();

await testAsync('3.6.3.1', ' Auth0 error parameter renders error page', async () => {
  console.log('  Sending GET /auth/callback?error=access_denied&error_description=User+denied');
  console.log('  Auth0 sends error and error_description when the user cancels login');
  console.log('  The server should render an error page, not crash');
  console.log('  Checking: response status is not 500');
  var res = await fetch(BASE + '/auth/callback?error=access_denied&error_description=User+denied+access', TIMEOUT);
  check('Auth0 error handled', res.status !== 500, 'not 500', String(res.status));
});

await testAsync('3.6.3.2', ' Error response has Content-Type', async () => {
  console.log('  The error page should be HTML with correct Content-Type');
  console.log('  Checking: Content-Type is text/html');
  var res = await fetch(BASE + '/auth/callback?error=access_denied&error_description=test', TIMEOUT);
  var ct = res.headers.get('content-type') || '';
  check('Error page Content-Type', ct.includes('text/html') || ct.includes('application/json'), 'html or json', ct);
});

await testAsync('3.6.3.3', ' Error parameters are escaped in response', async () => {
  console.log('  Sending error=<script>alert(1)</script> — XSS in error parameter');
  console.log('  The error value must be HTML-escaped before rendering');
  console.log('  Checking: response does not contain raw <script> tag');
  var res = await fetch(BASE + '/auth/callback?error=' + encodeURIComponent('<script>alert(1)</script>'), TIMEOUT);
  var body = await res.text();
  check('XSS in error escaped', !body.includes('<script>alert(1)'), 'escaped', 'RAW SCRIPT');
});

await testAsync('3.6.3.4', ' Security headers present on error response', async () => {
  console.log('  Even error pages must include security headers');
  console.log('  Checking: X-Frame-Options and X-Content-Type-Options present');
  var res = await fetch(BASE + '/auth/callback?error=test', TIMEOUT);
  var xfo = res.headers.get('x-frame-options');
  var xcto = res.headers.get('x-content-type-options');
  check('X-Frame-Options on error', xfo === 'DENY', 'DENY', String(xfo));
  check('X-Content-Type-Options on error', xcto === 'nosniff', 'nosniff', String(xcto));
});

var after3 = getCounters();
groupEnd(after3.pass - before3.pass, after3.fail - before3.fail);

var summary = getCounters();
process.exit(summary.fail);
