// Step 2 Groups 3, 4, 5: Auth0 OAuth Flow
// State management + login URL + logout URL construction
// ═══════════════════════════════════════════════════════════════

import { group, groupEnd, test, check, getCounters } from '../lib/test-harness.mjs';
import auth0 from '../../../src/auth/providers/auth0.js';

// ── Group 3: OAuth state management ──────────────────────────

group('Group 3: OAuth state management', `
  If these tests fail, the login flow is vulnerable to CSRF
  attacks. An attacker could forge OAuth redirects and hijack
  a user's session — gaining full access to their account.
`);

var before3 = getCounters();

test('3.2.3.1', '', () => {
  console.log('  Generating CSRF state via auth0._generateState()');
  var s1 = auth0._generateState();
  console.log('  Returned: ' + s1.substring(0, 16) + '...');
  check('State is a string', typeof s1 === 'string', 'string', typeof s1);
});

test('3.2.3.2', '', () => {
  console.log('  State must be 64 hex chars = 256 bits of entropy');
  console.log('  Makes brute-force prediction computationally infeasible');
  var s1 = auth0._generateState();
  check('State is 256-bit', /^[0-9a-f]{64}$/.test(s1), '64 hex chars', s1.length + ' chars');
  auth0._validateState(s1); // consume
});

test('3.2.3.3', '', () => {
  console.log('  Generating two states and comparing — must never be identical');
  var s1 = auth0._generateState();
  var s2 = auth0._generateState();
  console.log('  State 1: ' + s1.substring(0, 12) + '...  State 2: ' + s2.substring(0, 12) + '...');
  check('Two states are never identical', s1 !== s2, 'different', 'identical');
  auth0._validateState(s1); auth0._validateState(s2); // consume
});

test('3.2.3.4', '', () => {
  console.log('  Validating a state — first use should succeed');
  var s = auth0._generateState();
  check('Valid state accepted on first use', auth0._validateState(s), 'true', 'false');
});

test('3.2.3.5', '', () => {
  console.log('  Same state second time — single-use enforcement prevents replay');
  var s = auth0._generateState();
  auth0._validateState(s);
  check('Same state rejected (single-use)', !auth0._validateState(s), 'false (consumed)', 'true (reusable)');
});

test('3.2.3.6', '', () => { check('Null state rejected', !auth0._validateState(null), 'false', 'true'); });
test('3.2.3.7', '', () => { check('Undefined state rejected', !auth0._validateState(undefined), 'false', 'true'); });
test('3.2.3.8', '', () => { check('Empty string rejected', !auth0._validateState(''), 'false', 'true'); });

test('3.2.3.9', '', () => {
  console.log('  Passing attacker-crafted string — never generated by our server');
  check('Attacker string rejected', !auth0._validateState('not-a-real-state'), 'false', 'true');
});

test('3.2.3.10', '', () => { check('Numeric value rejected', !auth0._validateState(12345), 'false', 'true'); });

test('3.2.3.11', '', () => {
  console.log('  Generating 10 states, shuffling, validating in random order');
  var states = [];
  for (var i = 0; i < 10; i++) states.push(auth0._generateState());
  var shuffled = states.sort(() => Math.random() - 0.5);
  var allValid = true;
  for (var s of shuffled) { if (!auth0._validateState(s)) allValid = false; }
  check('10 states validated in random order', allValid, 'all valid', 'some invalid');
});

test('3.2.3.12', '', () => {
  console.log('  Re-validating consumed states — all must fail');
  var states = [];
  for (var i = 0; i < 10; i++) states.push(auth0._generateState());
  for (var s of states) auth0._validateState(s);
  var allInvalid = true;
  for (var s2 of states) { if (auth0._validateState(s2)) allInvalid = false; }
  check('All 10 reject second validation', allInvalid, 'all rejected', 'some accepted');
});

var after3 = getCounters();
groupEnd(after3.pass - before3.pass, after3.fail - before3.fail);

// ── Group 4: Login URL construction ──────────────────────────

group('Group 4: Login URL construction', `
  If these tests fail, clicking 'Log in' sends users to a
  malformed Auth0 URL. Login fails for every user — the
  platform is completely inaccessible.
`);

var before4 = getCounters();
process.env.AUTH0_DOMAIN = 'my-tenant.auth0.com'; process.env.AUTH0_CLIENT_ID = 'client_abc123';
process.env.AUTH0_CLIENT_SECRET = 'secret'; process.env.AUTH0_AUDIENCE = 'https://my-api';
process.env.AUTH0_REDIRECT_URI = 'https://app.example.com/auth/callback';
process.env.AUTH0_SCOPES = 'openid profile email offline_access';

test('3.2.4.1', '', () => {
  var url = auth0.getLoginUrl('state_xyz');
  var parsed = new URL(url);
  console.log('  Generated login URL, checking HTTPS');
  check('Login URL uses HTTPS', parsed.protocol === 'https:', 'https:', parsed.protocol);
});

test('3.2.4.2', '', () => {
  var parsed = new URL(auth0.getLoginUrl('state_xyz'));
  check('Targets correct domain', parsed.hostname === 'my-tenant.auth0.com', 'my-tenant.auth0.com', parsed.hostname);
});

test('3.2.4.3', '', () => {
  var parsed = new URL(auth0.getLoginUrl('state_xyz'));
  check('Uses /authorize endpoint', parsed.pathname === '/authorize', '/authorize', parsed.pathname);
});

test('3.2.4.4', '', () => {
  var parsed = new URL(auth0.getLoginUrl('state_xyz'));
  console.log('  response_type=code means authorization code flow (more secure than implicit)');
  check('Requests code flow', parsed.searchParams.get('response_type') === 'code', 'code', parsed.searchParams.get('response_type'));
});

test('3.2.4.5', '', () => {
  var parsed = new URL(auth0.getLoginUrl('state_xyz'));
  check('Includes client ID', parsed.searchParams.get('client_id') === 'client_abc123', 'client_abc123', parsed.searchParams.get('client_id'));
});

test('3.2.4.6', '', () => {
  var parsed = new URL(auth0.getLoginUrl('state_xyz'));
  check('Includes callback redirect', parsed.searchParams.get('redirect_uri') === 'https://app.example.com/auth/callback', 'https://app.example.com/auth/callback', parsed.searchParams.get('redirect_uri'));
});

test('3.2.4.7', '', () => {
  var parsed = new URL(auth0.getLoginUrl('state_xyz'));
  check('Includes OIDC scopes', parsed.searchParams.get('scope') === 'openid profile email offline_access', 'openid profile email offline_access', parsed.searchParams.get('scope'));
});

test('3.2.4.8', '', () => {
  var parsed = new URL(auth0.getLoginUrl('state_xyz'));
  check('Includes API audience', parsed.searchParams.get('audience') === 'https://my-api', 'https://my-api', parsed.searchParams.get('audience'));
});

test('3.2.4.9', '', () => {
  var parsed = new URL(auth0.getLoginUrl('state_xyz'));
  check('Includes CSRF state', parsed.searchParams.get('state') === 'state_xyz', 'state_xyz', parsed.searchParams.get('state'));
});

test('3.2.4.10', '', () => {
  console.log('  Calling getLoginUrl() with no state — should auto-generate');
  var parsed = new URL(auth0.getLoginUrl());
  var autoState = parsed.searchParams.get('state');
  check('State auto-generated', autoState && /^[0-9a-f]{64}$/.test(autoState), '64 hex chars', String(autoState?.length) + ' chars');
  if (autoState) auth0._validateState(autoState);
});

test('3.2.4.11', '', () => {
  console.log('  Removing AUTH0_REDIRECT_URI, setting DASHBOARD_PORT=4000');
  delete process.env.AUTH0_REDIRECT_URI; process.env.DASHBOARD_PORT = '4000';
  var url = auth0.getLoginUrl('s');
  check('Default redirect uses DASHBOARD_PORT', url.includes('localhost%3A4000') || url.includes('localhost:4000'), 'contains port 4000', 'see URL');
  delete process.env.DASHBOARD_PORT;
});

delete process.env.AUTH0_DOMAIN; delete process.env.AUTH0_CLIENT_ID; delete process.env.AUTH0_CLIENT_SECRET;
delete process.env.AUTH0_AUDIENCE; delete process.env.AUTH0_SCOPES;
var after4 = getCounters();
groupEnd(after4.pass - before4.pass, after4.fail - before4.fail);

// ── Group 5: Logout URL construction ─────────────────────────

group('Group 5: Logout URL construction', `
  If these tests fail, users cannot log out. Sessions persist
  indefinitely — on shared devices, the next person has full
  access to the previous user's account.
`);

var before5 = getCounters();
process.env.AUTH0_DOMAIN = 'my-tenant.auth0.com'; process.env.AUTH0_CLIENT_ID = 'client_abc123';
process.env.AUTH0_CLIENT_SECRET = 'secret'; process.env.AUTH0_LOGOUT_URI = 'https://app.example.com/';

test('3.2.5.1', '', () => {
  var parsed = new URL(auth0.getLogoutUrl('https://app.example.com/goodbye'));
  check('Logout URL uses HTTPS', parsed.protocol === 'https:', 'https:', parsed.protocol);
});

test('3.2.5.2', '', () => {
  var parsed = new URL(auth0.getLogoutUrl('https://app.example.com/goodbye'));
  check('Targets correct domain', parsed.hostname === 'my-tenant.auth0.com', 'my-tenant.auth0.com', parsed.hostname);
});

test('3.2.5.3', '', () => {
  var parsed = new URL(auth0.getLogoutUrl('https://app.example.com/goodbye'));
  check('Uses /v2/logout endpoint', parsed.pathname === '/v2/logout', '/v2/logout', parsed.pathname);
});

test('3.2.5.4', '', () => {
  var parsed = new URL(auth0.getLogoutUrl('https://app.example.com/goodbye'));
  check('Includes client ID', parsed.searchParams.get('client_id') === 'client_abc123', 'client_abc123', parsed.searchParams.get('client_id'));
});

test('3.2.5.5', '', () => {
  var parsed = new URL(auth0.getLogoutUrl('https://app.example.com/goodbye'));
  check('Redirects to specified destination', parsed.searchParams.get('returnTo') === 'https://app.example.com/goodbye', 'https://app.example.com/goodbye', parsed.searchParams.get('returnTo'));
});

test('3.2.5.6', '', () => {
  console.log('  Calling getLogoutUrl() with no argument — should use AUTH0_LOGOUT_URI');
  var parsed = new URL(auth0.getLogoutUrl());
  check('Default uses AUTH0_LOGOUT_URI', parsed.searchParams.get('returnTo') === 'https://app.example.com/', 'https://app.example.com/', parsed.searchParams.get('returnTo'));
});

delete process.env.AUTH0_DOMAIN; delete process.env.AUTH0_CLIENT_ID; delete process.env.AUTH0_CLIENT_SECRET; delete process.env.AUTH0_LOGOUT_URI;
var after5 = getCounters();
groupEnd(after5.pass - before5.pass, after5.fail - before5.fail);

// ── Exit ─────────────────────────────────────────────────────
var summary = getCounters();
process.exit(summary.fail);
